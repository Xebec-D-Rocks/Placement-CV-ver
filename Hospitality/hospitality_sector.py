# Function to compute new revenue and satisfaction under each policy
def compute_policy_values(row):
    # If not cancelled (days_cancelled_in_advance is missing), return original revenue and NaNs for satisfaction
    if pd.isna(row['days_cancelled_in_advance']):
        original = row['total_revenue_generated']
        return pd.Series([original, original, original, pd.NA, pd.NA, pd.NA])

    days = int(row['days_cancelled_in_advance'])
    original = row['total_revenue_generated']

    # Policy 1
    if days <= 1:
        refund1 = 0.10
        score1 = 4
    elif 2 <= days <= 7:
        refund1 = 0.50
        score1 = 8
    else:  # 8+
        refund1 = 0.90
        score1 = 12

    # Policy 2
    if days <= 1:
        refund2 = 0.20
        score2 = 5
    elif 2 <= days <= 7:
        refund2 = 0.50
        score2 = 8
    else:
        refund2 = 0.80
        score2 = 11

    # Policy 3
    if days == 0:
        refund3 = 0.10
        score3 = 3
    elif days in [1, 2]:
        refund3 = 0.30
        score3 = 6
    elif 3 <= days <= 7:
        refund3 = 0.60
        score3 = 9
    else:
        refund3 = 0.90
        score3 = 12

    rev1 = int(original * (1 - refund1))
    rev2 = int(original * (1 - refund2))
    rev3 = int(original * (1 - refund3))

    return pd.Series([rev1, rev2, rev3, score1, score2, score3])

