# Step 2: Estimate days cancelled in advance based on booking lead time
def estimate_cancel_days(x):
    """
    Estimations:
    - If booked ≥8 days → cancel ~40% of lead time
    - If booked 2–7 days → ~60%
    - If booked <2 days → ~80%
    Logic uses truncation (int) to avoid rounding up.
    """
    adv = x['days_booked_in_advance']
    if adv >= 8:
        return int(adv * 0.4)
    elif adv >= 2:
        return int(adv * 0.6)
    elif adv >= 0:
        return int(adv * 0.8)
    else:
        return pd.NA  # safeguard

